const TARGET = 2100;
// round-robin the wells until we comfortably exceed the target
const wells = [wellSimiles(), wellGadget(), wellCheer(), wellWonder()];
let wIdx = 0;
function* roundRobin() {
  const live = wells.slice();
  while (live.length) {
    for (let i = live.length - 1; i >= 0; i--) {
      const { value, done } = live[i].next();
      if (done) { live.splice(i, 1); continue; }
      yield value;
    }
  }
}
for (const line of roundRobin()) {
  if (set.size >= TARGET) break;
  push(line);
}

